#!/usr/bin/env python3
import os
import sys
import subprocess
import shutil
import urllib.request
import glob

def print_step(msg):
    print(f"\n\033[94m==> {msg}\033[0m")

def build_appdir():
    print_step("Building AppDir via JetBrains Compose")

    if not os.path.exists("gradlew"):
        print("❌ 'gradlew' not found. Are you sure you are in the project root?")
        sys.exit(1)

    os.chmod("gradlew", 0o755)

    print("Running Gradle 'packageAppImage'...")
    subprocess.run(["./gradlew", "packageAppImage"], check=True)

def prepare_and_pack():
    print_step("Preparing AppDir for packing")

    # 1. Locate the generated AppDir (usually out/main/app/<app-name>)
    appdirs = glob.glob("out/main/app/*")
    if not appdirs:
        print("❌ Could not find the generated AppDir in 'out/main/app/'.")
        print("   If the Gradle build failed, fix the errors above first.")
        sys.exit(1)

    appdir_path = appdirs[0]
    print(f"Found AppDir at: {appdir_path}")

    # 2. Ensure AppRun exists and points to the correct executable
    apprun_path = os.path.join(appdir_path, "AppRun")
    if not os.path.exists(apprun_path):
        print("Creating missing AppRun symlink...")
        bin_dir = os.path.join(appdir_path, "bin")
        exec_file = "btrfs-file-restorer" # fallback

        # Find the actual executable generated by Compose
        if os.path.exists(bin_dir):
            for f in os.listdir(bin_dir):
                if os.path.isfile(os.path.join(bin_dir, f)):
                    exec_file = f
                    break

        os.symlink(f"bin/{exec_file}", apprun_path)
    os.chmod(apprun_path, 0o755)

    # 3. Ensure Icon is present in the AppDir root
    project_icon = "btrfs-file-restorer.png"
    appdir_icon = os.path.join(appdir_path, "btrfs-file-restorer.png")

    icon_name = "btrfs-file-restorer"
    appdir_icons = glob.glob(os.path.join(appdir_path, "*.png")) + glob.glob(os.path.join(appdir_path, "*.svg"))

    if appdir_icons:
        icon_name = os.path.splitext(os.path.basename(appdir_icons[0]))[0]
    elif os.path.exists(project_icon):
        shutil.copy(project_icon, appdir_icon)

    # 4. Generate a valid .desktop file in the AppDir root
    desktop_path = os.path.join(appdir_path, "btrfs-file-restorer.desktop")
    print(f"Writing standard .desktop file (Icon={icon_name})...")

    with open(desktop_path, "w") as f:
        f.write(f"""[Desktop Entry]
Name=Btrfs File Restorer
Comment=Restores files from unmountable btrfs filesystem
Exec=btrfs-file-restorer
Icon={icon_name}
Type=Application
Categories=Utility;System;
Terminal=false
""")

    # 5. Download appimagetool if missing
    tool_name = "appimagetool-x86_64.AppImage"
    if not os.path.exists(tool_name):
        print("Downloading appimagetool...")
        urllib.request.urlretrieve("https://github.com/AppImage/appimagetool/releases/download/continuous/appimagetool-x86_64.AppImage", tool_name)
        os.chmod(tool_name, 0o755)

    # 6. Pack it into a single file
    output_file = "Btrfs-File-Restorer.AppImage"
    print(f"Sealing AppDir into {output_file}...")

    env = os.environ.copy()
    env["ARCH"] = "x86_64"

    subprocess.run([f"./{tool_name}", appdir_path, output_file], env=env, check=True)

    print(f"\n\033[92m✅ SUCCESS! AppImage generated:\033[0m")
    print(f"   Location: {os.path.abspath(output_file)}")
    print(f"   Run with: ./{output_file}")

if __name__ == "__main__":
    print("===================================================")
    print("    AppImage Generator for Btrfs-File-Restorer")
    print("===================================================")

    # Run gradle build only if the AppDir doesn't exist yet
    if not os.path.exists("out/main/app"):
        build_appdir()
    else:
        print_step("Skipping Gradle build (AppDir already exists)")

    prepare_and_pack()
